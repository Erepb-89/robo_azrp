"""Конфигурация паллета-полок (паллетирование).

Паллет — стол с тремя выдвижными полками (верх, середина, низ). На каждой
полке один слой 4 x 2 = 8 ячеек. Полки выдвигаются роботом крючком (без
участия гриппера) до срабатывания концевика DI.SHELF_n. Порядок работы:
верх -> середина -> низ.

ВСЕ геометрические и кинематические параметры — заглушки None. Заполняются
после обучения точек и прозвонки концевиков; код править не требуется.

Новые файлы паллетирования:
- pallet_cfg.py   — этот файл (параметры);
- shelf_io.py     — соответствие полок и входов DI.SHELF_n;
- shelf_motion.py — движение к ячейкам и выдвижение крючком (guarded jog);
- pallet_errors.py— перечисление ошибок паллета;
- pallet_manager.py — модель полок/ячеек и логика паллетирования.
"""

# Порядок полок: верх -> середина -> низ.
# Верх = DI.SHELF_1 (21), середина = DI.SHELF_2 (22), низ = DI.SHELF_3 (23).
SHELF_ORDER = [1, 2, 3]

ROWS = 2   # число рядов ячеек на полке (вдоль +Y)
COLS = 4   # число столбцов ячеек на полке (вдоль +X)

PALLET_CFG = {
    "shelves": list(SHELF_ORDER),
    "rows": ROWS,
    "cols": COLS,

    # Общая базовая точка — обученная точка ячейки (row=0, col=0) верхней
    # полки. Имя точки в points.json. Заглушка.
    "origin_point": None,

    # Шаги сетки между ячейками, м.
    "pitch_x": None,   # вдоль +X, 4 ячейки
    "pitch_y": None,   # вдоль +Y, 2 ячейки

    # Вертикальное смещение каждой полки относительно origin_point, м
    # (насколько полка ниже/выше базовой). Заглушки.
    "shelf_dz": {1: None, 2: None, 3: None},

    # Высоты относительно позы ячейки, м.
    "cell_approach_dz": None,  # высота подхода/отхода над ячейкой
    "cell_dwell_dz": None,     # рабочая высота (0 => поза ячейки)

    # Скорости перемещения к ячейкам паллета (м/с, м/с^2, м).
    "cell_speed": 0.1,
    "cell_accel": 0.1,
    "cell_blend": 0.0,

    # Выдвижение полки крючком: ось/направление/таймаут. Заглушки.
    "pull_axis": None,         # 'X' | 'Y' | 'Z' | 'Rx' | 'Ry' | 'Rz'
    "pull_dir": None,          # '+' | '-'
    "pull_timeout_sec": None,  # сек

    # Обученные точки крючка на каждую полку (имена точек points.json).
    # approach — безопасный подъезд, engage — зацеп, retreat — отход после
    # вытягивания, closed — точка задвинутой полки. Заглушки.
    "hook": {
        1: {"approach": None, "engage": None, "retreat": None, "closed": None},
        2: {"approach": None, "engage": None, "retreat": None, "closed": None},
        3: {"approach": None, "engage": None, "retreat": None, "closed": None},
    },

    # Строгий режим:
    #   False (заглушка) — отсутствие параметров/точек лишь логируется,
    #     движение по паллету пропускается (для SIM и пусконаладки);
    #   True — отсутствие любых параметров/точек = ошибка цикла.
    "strict": False,
}
